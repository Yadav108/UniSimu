"""Bake quadratic limb-darkening coefficients into unisimu/physics/limb_darkening_data.py.

Offline tool, not imported by the app. Usage (from the repo root):

    python tools/build_limb_darkening.py path/to/tableab.dat.gz

Input: Claret & Bloemen (2011), A&A 529, A75, VizieR catalogue J/A+A/529/A75,
file tableab.dat (https://cdsarc.cds.unistra.fr/ftp/J/A+A/529/A75/). Quadratic
law I(mu)/I(1) = 1 - a(1 - mu) - b(1 - mu)^2.

Selection: ATLAS models, solar metallicity (log[M/H] = 0), microturbulence
2 km/s, least-squares fits (Met = L), Johnson B, V and R -- the passbands
nearest the blue, green and red sRGB primaries. ATLAS has no models for hot,
low-gravity stars (beyond the Eddington limit); those grid cells take the
nearest available log g at the same temperature. Equations and sources:
docs/physics/equations/03-stellar-surface.md.
"""

import gzip
import sys
from pathlib import Path

FILTERS = ("R ", "V ", "B ")  # -> red, green, blue channel
OUT = Path(__file__).resolve().parents[1] / "unisimu" / "physics" / "limb_darkening_data.py"


def read_rows(path: Path):
    """Yield (logg, teff, filter, a, b) for the selected models (byte layout from the ReadMe)."""
    opener = gzip.open if path.suffix == ".gz" else open
    with opener(path, "rt", encoding="ascii") as handle:
        for line in handle:
            if line[44:51].strip() != "ATLAS" or line[42] != "L":
                continue
            if float(line[13:17]) != 0.0 or float(line[18:22]) != 2.0:
                continue
            band = line[39:41]
            if band in FILTERS:
                yield float(line[0:5]), float(line[6:12]), band, float(line[23:30]), float(line[31:38])


def build(rows) -> tuple[list[float], list[float], dict]:
    table: dict[tuple[float, float, str], tuple[float, float]] = {}
    for logg, teff, band, a, b in rows:
        table[(teff, logg, band)] = (a, b)
    teffs = sorted({k[0] for k in table})
    loggs = sorted({k[1] for k in table})
    grid = {}
    for teff in teffs:
        for logg in loggs:
            coeffs = []
            for band in FILTERS:
                if (teff, logg, band) in table:
                    coeffs.append(table[(teff, logg, band)])
                else:
                    nearest = min(
                        (g for g in loggs if (teff, g, band) in table), key=lambda g: abs(g - logg)
                    )
                    coeffs.append(table[(teff, nearest, band)])
            # (a_R, a_G, a_B, b_R, b_G, b_B)
            grid[(teff, logg)] = tuple(c[0] for c in coeffs) + tuple(c[1] for c in coeffs)
    return teffs, loggs, grid


def render(teffs, loggs, grid) -> str:
    lines = [
        '"""Quadratic limb-darkening coefficients, generated by tools/build_limb_darkening.py.',
        "",
        "Source: Claret & Bloemen (2011), A&A 529, A75 (VizieR J/A+A/529/A75), ATLAS",
        "models, log[M/H] = 0, xi = 2 km/s, least-squares fits, Johnson R, V, B for the",
        "red, green, blue channels. Do not edit by hand -- rerun the tool.",
        '"""',
        "",
        f"TEFF_K = {tuple(teffs)!r}",
        f"LOGG_CGS = {tuple(loggs)!r}",
        "# COEFFS[i][j] = (a_R, a_G, a_B, b_R, b_G, b_B) at TEFF_K[i], LOGG_CGS[j]",
        "COEFFS = (",
    ]
    for teff in teffs:
        row = ", ".join("(" + ", ".join(f"{v:.4f}" for v in grid[(teff, g)]) + ")" for g in loggs)
        lines.append(f"    ({row}),")
    lines.append(")")
    return "\n".join(lines) + "\n"


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    teffs, loggs, grid = build(read_rows(Path(sys.argv[1])))
    OUT.write_text(render(teffs, loggs, grid), encoding="utf-8")
    print(f"wrote {OUT}: {len(teffs)} Teff x {len(loggs)} log g grid")


if __name__ == "__main__":
    main()
